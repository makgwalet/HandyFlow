import { describe, it, expect, vi, beforeEach, afterEach } from "vitest"
import { render, screen, cleanup, within, fireEvent, waitFor } from "@testing-library/react"
import { QueryClient, QueryClientProvider } from "@tanstack/react-query"
import CampaignsPanel from "./CampaignsPanel"
import {
  EMPTY_CAMPAIGN, NEXT_STATUS, addBody, addProblem, addedText, campaignBody, campaignProblem, peopleLocked, progressText, rate, runSummary, stepsBody, stepsLocked, stepsProblem,
  type Campaign, type JourneyRun, type JourneyStep, type Person, type StepForm,
} from "./campaigns.logic"

const get = vi.fn(), post = vi.fn(), put = vi.fn(), del = vi.fn()
let perms = new Set<string>()
vi.mock("../../api/client", () => ({ apiClient: { get: (...a: unknown[]) => get(...a), post: (...a: unknown[]) => post(...a), put: (...a: unknown[]) => put(...a), delete: (...a: unknown[]) => del(...a) } }))
vi.mock("../../hooks/usePermission", () => ({ usePermission: (p: string) => perms.has(p) }))
const wrap = (ui: React.ReactElement) => render(<QueryClientProvider client={new QueryClient({ defaultOptions: { queries: { retry: false } } })}>{ui}</QueryClientProvider>)
const ok = (d: unknown) => Promise.resolve({ data: { data: d } })
beforeEach(() => { perms = new Set(["CUSTOMER_READ", "CUSTOMER_UPDATE"]); for (const m of [get, post, put, del]) { m.mockReset() } for (const m of [post, put, del]) { m.mockResolvedValue({ data: { data: {} } }) } })
afterEach(cleanup)

const camp = (over: Partial<Campaign> = {}): Campaign => ({ id: "k1", name: "Spring push", goal: "Win back lapsed leads", status: "DRAFT", startsOn: "2026-10-01", endsOn: "2026-10-31", steps: 2, total: 4, contacted: 3, responded: 2, converted: 1, responseRate: 50, conversionRate: 25, ...over })
const step = (over: Partial<JourneyStep> = {}): JourneyStep => ({ position: 1, dayOffset: 0, action: "CREATE_TASK", text: "Call", user: null, description: "Straight away: add the task \"Call\"", ...over })
const person = (over: Partial<Person> = {}): Person => ({ id: "m1", customerId: "c1", name: "Acme", status: "ADDED", addedAt: "2026-10-01T08:00:00Z", statusAt: "2026-10-01T08:00:00Z", stepsDone: 1, exited: false, ...over })
const run = (over: Partial<JourneyRun> = {}): JourneyRun => ({ id: "r1", customerId: "c1", customerName: "Acme", step: 1, outcome: "DONE", detail: "Task added, due 2026-10-23", ranAt: "2026-10-21T10:00:00Z", ...over })
const users = { content: [{ id: "u1", firstName: "Olive", lastName: "Other" }] }
function serve(o: { camps?: Campaign[]; steps?: JourneyStep[]; people?: Person[]; runs?: JourneyRun[]; found?: unknown } = {}) {
  get.mockImplementation((url: string) => {
    if (url.endsWith("/steps")) return ok(o.steps ?? [])
    if (url.endsWith("/people")) return ok(o.people ?? [])
    if (url.endsWith("/runs")) return ok(o.runs ?? [])
    if (url.includes("/segments")) return ok([{ id: "s1", name: "Hot leads", count: 12 }])
    if (url.includes("/identity/users")) return ok(users)
    if (url.includes("/crm/customers")) return ok(o.found ?? [])
    return ok(o.camps ?? [])
  })
}

describe("campaign logic", () => {
  it("checks the campaign form", () => {
    expect(campaignProblem(EMPTY_CAMPAIGN)).toBe("Name the campaign.")
    expect(campaignProblem({ ...EMPTY_CAMPAIGN, name: "x".repeat(121) })).toBe("The name can be at most 120 characters.")
    expect(campaignProblem({ ...EMPTY_CAMPAIGN, name: "x", goal: "g".repeat(501) })).toBe("The goal can be at most 500 characters.")
    expect(campaignProblem({ ...EMPTY_CAMPAIGN, name: "x", startsOn: "2026-10-31", endsOn: "2026-10-01" })).toBe("The end date cannot be before the start date.")
    expect(campaignProblem({ ...EMPTY_CAMPAIGN, name: "x" })).toBeNull()
    expect(campaignBody({ name: " Spring ", goal: " ", startsOn: "", endsOn: "2026-10-31" })).toEqual({ name: "Spring", goal: null, startsOn: null, endsOn: "2026-10-31" })
  })
  it("offers the moves the server allows", () => {
    expect(NEXT_STATUS.DRAFT.map(n => n.label)).toEqual(["Start"])
    expect(NEXT_STATUS.ACTIVE.map(n => n.label)).toEqual(["Pause", "Finish"])
    expect(NEXT_STATUS.PAUSED.map(n => n.label)).toEqual(["Resume", "Finish"])
    expect(NEXT_STATUS.COMPLETED).toEqual([])
    expect(stepsLocked("ACTIVE") && stepsLocked("COMPLETED") && !stepsLocked("DRAFT") && !stepsLocked("PAUSED")).toBe(true)
    expect(peopleLocked("COMPLETED") && !peopleLocked("ACTIVE")).toBe(true)
  })
  it("checks the steps one by one", () => {
    const s = (over: Partial<StepForm> = {}): StepForm => ({ day: "0", action: "ADD_TAG", text: "warm", user: "", ...over })
    expect(stepsProblem([])).toBeNull()
    expect(stepsProblem([s(), s({ day: "3" })])).toBeNull()
    expect(stepsProblem(Array.from({ length: 11 }, () => s()))).toBe("A journey can have at most 10 steps.")
    expect(stepsProblem([s({ day: "" })])).toBe("Step 1: the day must be a whole number from 0 to 365.")
    expect(stepsProblem([s({ day: "366" })])).toBe("Step 1: the day must be a whole number from 0 to 365.")
    expect(stepsProblem([s({ day: "1.5" })])).toBe("Step 1: the day must be a whole number from 0 to 365.")
    expect(stepsProblem([s({ day: "5" }), s({ day: "2" })])).toBe("Step 2: it cannot come before the step above it.")
    expect(stepsProblem([s({ action: "" })])).toBe("Step 1: choose what it does.")
    expect(stepsProblem([s({ action: "CREATE_TASK", text: " " })])).toBe("Step 1: say what the task is.")
    expect(stepsProblem([s({ text: "x".repeat(51) })])).toBe("Step 1: the tag can be at most 50 characters.")
    expect(stepsProblem([s({ action: "ASSIGN_OWNER", text: "" })])).toBe("Step 1: choose who becomes the owner.")
    expect(stepsProblem([s({ action: "NOTIFY_OWNER", text: "" })])).toBe("Step 1: write the message.")
  })
  it("sends only what each step uses", () => {
    expect(stepsBody([{ day: " 3 ", action: "ADD_TAG", text: " warm ", user: "u1" }, { day: "7", action: "ASSIGN_OWNER", text: "x", user: "u1" }, { day: "8", action: "CREATE_TASK", text: "Call", user: "" }]))
      .toEqual([{ dayOffset: 3, action: "ADD_TAG", text: "warm", user: null }, { dayOffset: 7, action: "ASSIGN_OWNER", text: null, user: "u1" }, { dayOffset: 8, action: "CREATE_TASK", text: "Call", user: null }])
  })
  it("checks and words adding people", () => {
    expect(addProblem("", [])).toBe("Choose a segment or pick some people.")
    expect(addProblem("s1", [])).toBeNull()
    expect(addProblem("", ["c1"])).toBeNull()
    expect(addProblem("", Array.from({ length: 501 }, (_, i) => String(i)))).toBe("Add at most 500 people at a time.")
    expect(addBody("", ["c1"])).toEqual({ segmentId: null, customerIds: ["c1"] })
    expect(addedText({ added: 1, alreadyIn: 0, skipped: 0 })).toBe("1 person added.")
    expect(addedText({ added: 3, alreadyIn: 2, skipped: 1 })).toBe("3 people added, 2 already in, 1 could not be found.")
  })
  it("words progress, rates and the log", () => {
    expect(progressText(person({ stepsDone: 1 }), 3)).toBe("1 of 3 steps")
    expect(progressText(person({ stepsDone: 1, exited: true }), 3)).toBe("Left the journey")
    expect(progressText(person({ stepsDone: 3, exited: true }), 3)).toBe("3 of 3 steps")
    expect(progressText(person(), 0)).toBe("No steps")
    expect(rate(null)).toBe("—")
    expect(rate(50)).toBe("50%")
    expect(runSummary([run(), run({ id: "r2", outcome: "FAILED" })])).toEqual({ done: 1, failed: 1 })
  })
})

describe("CampaignsPanel", () => {
  it("lists campaigns with their numbers", async () => {
    serve({ camps: [camp()] })
    wrap(<CampaignsPanel />)
    const row = await screen.findByRole("listitem", { name: "Spring push" })
    expect(within(row).getByText("Draft")).toBeTruthy()
    expect(within(row).getByText("2 steps")).toBeTruthy()
    expect(within(row).getByText("Goal: Win back lapsed leads")).toBeTruthy()
    expect(within(row).getByText("2 responded (50%)")).toBeTruthy()
    expect(within(row).getByText("1 converted (25%)")).toBeTruthy()
  })
  it("creates a campaign", async () => {
    serve({ camps: [] })
    wrap(<CampaignsPanel />)
    fireEvent.click(await screen.findByRole("button", { name: "Add campaign" }))
    expect((screen.getByRole("button", { name: "Save campaign" }) as HTMLButtonElement).disabled).toBe(true)
    fireEvent.change(screen.getByLabelText("Campaign name"), { target: { value: "Spring push" } })
    fireEvent.change(screen.getByLabelText("Goal"), { target: { value: "Win back" } })
    fireEvent.click(screen.getByRole("button", { name: "Save campaign" }))
    await waitFor(() => expect(post).toHaveBeenCalledWith("/api/v1/crm/campaigns", { name: "Spring push", goal: "Win back", startsOn: null, endsOn: null }))
  })
  it("starts a draft and offers pause and finish while running", async () => {
    serve({ camps: [camp()] })
    wrap(<CampaignsPanel />)
    fireEvent.click(await screen.findByRole("button", { name: "Start Spring push" }))
    await waitFor(() => expect(put).toHaveBeenCalledWith("/api/v1/crm/campaigns/k1/status", { status: "ACTIVE" }))
    cleanup()
    serve({ camps: [camp({ status: "ACTIVE" })] })
    wrap(<CampaignsPanel />)
    expect(await screen.findByRole("button", { name: "Pause Spring push" })).toBeTruthy()
    expect(screen.getByRole("button", { name: "Finish Spring push" })).toBeTruthy()
    expect(screen.queryByRole("button", { name: "Delete Spring push" })).toBeNull()
  })
  it("shows the server's reason when a move is refused", async () => {
    serve({ camps: [camp()] })
    put.mockRejectedValue({ response: { data: { message: "Add people before starting the campaign" } } })
    wrap(<CampaignsPanel />)
    fireEvent.click(await screen.findByRole("button", { name: "Start Spring push" }))
    expect((await screen.findByRole("alert")).textContent).toContain("Add people before starting the campaign")
  })
  it("hides editing from people who can only read", async () => {
    perms = new Set(["CUSTOMER_READ"])
    serve({ camps: [camp()] })
    wrap(<CampaignsPanel />)
    await screen.findByRole("listitem", { name: "Spring push" })
    expect(screen.queryByRole("button", { name: "Add campaign" })).toBeNull()
    expect(screen.queryByRole("button", { name: "Start Spring push" })).toBeNull()
    expect(screen.queryByRole("button", { name: "Delete Spring push" })).toBeNull()
  })
  it("opens a campaign to show its steps, people and log", async () => {
    serve({ camps: [camp({ status: "PAUSED" })], steps: [step(), step({ position: 2, dayOffset: 3, action: "ADD_TAG", text: "warm", description: "After 3 days: tag it \"warm\"" })], people: [person()], runs: [run(), run({ id: "r2", outcome: "FAILED", detail: "The new owner is no longer a user" })] })
    wrap(<CampaignsPanel />)
    fireEvent.click(await screen.findByRole("button", { name: "Open Spring push" }))
    expect(await screen.findByText("Straight away: add the task \"Call\"")).toBeTruthy()
    expect(screen.getByText("After 3 days: tag it \"warm\"")).toBeTruthy()
    expect(await screen.findByText("1 of 2 steps")).toBeTruthy()
    expect(await screen.findByText("1 done, 1 failed in the last 2.")).toBeTruthy()
    expect(screen.getByText(/Failed: The new owner is no longer a user/)).toBeTruthy()
  })
  it("saves the steps", async () => {
    serve({ camps: [camp({ status: "PAUSED" })], steps: [step()] })
    wrap(<CampaignsPanel />)
    fireEvent.click(await screen.findByRole("button", { name: "Open Spring push" }))
    fireEvent.click(await screen.findByRole("button", { name: "Edit steps" }))
    fireEvent.click(screen.getByRole("button", { name: "Add step" }))
    fireEvent.change(screen.getByLabelText("Step 2 day"), { target: { value: "3" } })
    fireEvent.change(screen.getByLabelText("Step 2 action"), { target: { value: "ADD_TAG" } })
    fireEvent.change(screen.getByLabelText("Step 2 Tag"), { target: { value: "warm" } })
    fireEvent.click(screen.getByRole("button", { name: "Save steps" }))
    await waitFor(() => expect(put).toHaveBeenCalledWith("/api/v1/crm/campaigns/k1/steps", [
      { dayOffset: 0, action: "CREATE_TASK", text: "Call", user: null }, { dayOffset: 3, action: "ADD_TAG", text: "warm", user: null }]))
  })
  it("stops a step that would come before the one above", async () => {
    serve({ camps: [camp({ status: "PAUSED" })], steps: [step({ dayOffset: 5 })] })
    wrap(<CampaignsPanel />)
    fireEvent.click(await screen.findByRole("button", { name: "Open Spring push" }))
    fireEvent.click(await screen.findByRole("button", { name: "Edit steps" }))
    fireEvent.click(screen.getByRole("button", { name: "Add step" }))
    fireEvent.change(screen.getByLabelText("Step 2 day"), { target: { value: "2" } })
    fireEvent.change(screen.getByLabelText("Step 2 action"), { target: { value: "ADD_TAG" } })
    fireEvent.change(screen.getByLabelText("Step 2 Tag"), { target: { value: "warm" } })
    expect(screen.getByText("Step 2: it cannot come before the step above it.")).toBeTruthy()
    expect((screen.getByRole("button", { name: "Save steps" }) as HTMLButtonElement).disabled).toBe(true)
  })
  it("will not edit steps while the campaign is running", async () => {
    serve({ camps: [camp({ status: "ACTIVE" })], steps: [step()] })
    wrap(<CampaignsPanel />)
    fireEvent.click(await screen.findByRole("button", { name: "Open Spring push" }))
    expect(await screen.findByText("Pause the campaign to change its steps.")).toBeTruthy()
    expect(screen.queryByRole("button", { name: "Edit steps" })).toBeNull()
  })
  it("adds everyone in a segment", async () => {
    serve({ camps: [camp()] })
    post.mockResolvedValue({ data: { data: { added: 12, alreadyIn: 0, skipped: 0 } } })
    wrap(<CampaignsPanel />)
    fireEvent.click(await screen.findByRole("button", { name: "Open Spring push" }))
    const form = await screen.findByRole("form", { name: "Add people" })
    expect((within(form).getByRole("button", { name: "Add to campaign" }) as HTMLButtonElement).disabled).toBe(true)
    await within(form).findByRole("option", { name: "Hot leads (12)" })
    fireEvent.change(within(form).getByLabelText("Segment"), { target: { value: "s1" } })
    fireEvent.click(within(form).getByRole("button", { name: "Add to campaign" }))
    await waitFor(() => expect(post).toHaveBeenCalledWith("/api/v1/crm/campaigns/k1/people", { segmentId: "s1", customerIds: [] }))
    expect(await screen.findByText("12 people added.")).toBeTruthy()
  })
  it("finds people by name and adds them", async () => {
    serve({ camps: [camp()], found: { content: [{ id: "c9", name: "Zed Co" }] } })
    wrap(<CampaignsPanel />)
    fireEvent.click(await screen.findByRole("button", { name: "Open Spring push" }))
    const form = await screen.findByRole("form", { name: "Add people" })
    fireEvent.change(within(form).getByLabelText("Search customers"), { target: { value: "z" } })
    fireEvent.click(within(form).getByRole("button", { name: "Search" }))
    expect(await within(form).findByText("Type at least 2 letters of the customer's name.")).toBeTruthy()
    fireEvent.change(within(form).getByLabelText("Search customers"), { target: { value: "Zed" } })
    fireEvent.click(within(form).getByRole("button", { name: "Search" }))
    fireEvent.click(await within(form).findByRole("button", { name: "Pick Zed Co" }))
    fireEvent.click(within(form).getByRole("button", { name: "Add to campaign" }))
    await waitFor(() => expect(post).toHaveBeenCalledWith("/api/v1/crm/campaigns/k1/people", { segmentId: null, customerIds: ["c9"] }))
  })
  it("records a response and removes a person", async () => {
    serve({ camps: [camp({ status: "ACTIVE" })], people: [person()] })
    wrap(<CampaignsPanel />)
    fireEvent.click(await screen.findByRole("button", { name: "Open Spring push" }))
    fireEvent.change(await screen.findByLabelText("Status of Acme"), { target: { value: "RESPONDED" } })
    await waitFor(() => expect(put).toHaveBeenCalledWith("/api/v1/crm/campaigns/k1/people/m1/status", { status: "RESPONDED" }))
    fireEvent.click(screen.getByRole("button", { name: "Remove Acme" }))
    await waitFor(() => expect(del).toHaveBeenCalledWith("/api/v1/crm/campaigns/k1/people/m1"))
  })
  it("does not offer changes on a finished campaign", async () => {
    serve({ camps: [camp({ status: "COMPLETED" })], steps: [step()], people: [person()] })
    wrap(<CampaignsPanel />)
    fireEvent.click(await screen.findByRole("button", { name: "Open Spring push" }))
    expect(await screen.findByText("A finished campaign cannot be changed.")).toBeTruthy()
    await screen.findByText("1 of 1 steps")
    expect(screen.queryByRole("form", { name: "Add people" })).toBeNull()
    expect(screen.queryByRole("button", { name: "Edit Spring push" })).toBeNull()
    expect(screen.queryByLabelText("Status of Acme")).toBeNull()
  })
})
