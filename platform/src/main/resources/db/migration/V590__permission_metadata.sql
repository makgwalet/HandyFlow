-- V590: IAM Phase 1, item 1: permission metadata.
--
-- Adds the columns the target architecture asks for (docs/iam/IAM_TARGET_ARCHITECTURE.md, permissions table) and fills
-- them for every permission that exists today, one explicit row each so a person can review every decision.
--
--   module_key              the module that owns the permission; 'core' = platform / always available (users, roles,
--                           settings, billing, and the shared services approvals, evidence, records, control exceptions,
--                           the audit trail); 'unassigned' = a permission added without metadata (the build test fails on it)
--   resource, verb          the middle and last words of the name, for the People & Access matrix
--   sensitivity             NORMAL | SENSITIVE | FINANCIAL
--   requires_second_person  maker-checker intent: the step must not be done by the person who did the earlier one
--                           (enforced in code by SeparationOfDutiesChecker where wired; this flag drives the build rule)
--   grantable_by            OWNER | ADMIN | MODULE_ADMIN: who may hand the permission to someone else
--
-- Derived from the permission name by a prefix map, then checked against which controllers actually use each name
-- (no disagreements). To be reviewed by a person before it is relied on to drop permissions at login.

ALTER TABLE permissions
    ADD COLUMN IF NOT EXISTS module_key             VARCHAR(50) NOT NULL DEFAULT 'unassigned',
    ADD COLUMN IF NOT EXISTS resource               VARCHAR(60),
    ADD COLUMN IF NOT EXISTS verb                   VARCHAR(30),
    ADD COLUMN IF NOT EXISTS sensitivity            VARCHAR(10) NOT NULL DEFAULT 'NORMAL',
    ADD COLUMN IF NOT EXISTS requires_second_person BOOLEAN     NOT NULL DEFAULT false,
    ADD COLUMN IF NOT EXISTS grantable_by           VARCHAR(15) NOT NULL DEFAULT 'ADMIN';

ALTER TABLE permissions
    ADD CONSTRAINT ck_permissions_sensitivity CHECK (sensitivity IN ('NORMAL', 'SENSITIVE', 'FINANCIAL')),
    ADD CONSTRAINT ck_permissions_grantable_by CHECK (grantable_by IN ('OWNER', 'ADMIN', 'MODULE_ADMIN'));

CREATE INDEX IF NOT EXISTS idx_permissions_module_key ON permissions (module_key);

